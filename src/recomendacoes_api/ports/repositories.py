from typing import Protocol
from uuid import UUID

from recomendacoes_api.domain.entities import (
    Activity,
    Destination,
    Review,
    ScheduledActivity,
    Trip,
    User,
)


class UserRepository(Protocol):
    def find_by_id(self, user_id: UUID) -> User | None: ...

    def find_by_email(self, email: str) -> User | None: ...

    def list_by_ids(self, user_ids: list[UUID]) -> list[User]: ...

    def save(self, user: User) -> None: ...


class TripRepository(Protocol):
    def list_by_user(
        self, user_id: UUID, limit: int | None = None, offset: int = 0
    ) -> list[Trip]: ...

    def count_by_user(self, user_id: UUID) -> int: ...

    def find_by_id(self, trip_id: UUID) -> Trip | None: ...

    def find_by_invite_code(self, invite_code: str) -> Trip | None: ...

    def save(self, trip: Trip) -> None: ...

    def update(self, trip: Trip) -> None: ...

    def delete(self, trip_id: UUID) -> None: ...


class DestinationRepository(Protocol):
    def list_by_trip(
        self, trip_id: UUID, limit: int | None = None, offset: int = 0
    ) -> list[Destination]: ...

    def count_by_trip(self, trip_id: UUID) -> int: ...

    def find_by_id(self, destination_id: UUID) -> Destination | None: ...

    def save(self, destination: Destination) -> None: ...

    def update(self, destination: Destination) -> None: ...

    def update_many(self, destinations: list[Destination]) -> None: ...

    def delete(self, destination_id: UUID) -> None: ...


class ActivityRepository(Protocol):
    def list_all(self, limit: int | None = None, offset: int = 0) -> list[Activity]: ...

    def count_all(self) -> int: ...

    def list_by_ids(self, activity_ids: list[UUID]) -> list[Activity]: ...

    def find_by_id(self, activity_id: UUID) -> Activity | None: ...

    def save(self, activity: Activity) -> None: ...

    def update(self, activity: Activity) -> None: ...


class ScheduledActivityRepository(Protocol):
    def list_by_destination(
        self, destination_id: UUID, limit: int | None = None, offset: int = 0
    ) -> list[ScheduledActivity]: ...

    def count_by_destination(self, destination_id: UUID) -> int: ...

    def find_by_id(self, scheduled_id: UUID) -> ScheduledActivity | None: ...

    def save(self, scheduled: ScheduledActivity) -> None: ...

    def update(self, scheduled: ScheduledActivity) -> None: ...

    def delete(self, scheduled_id: UUID) -> None: ...


class ReviewRepository(Protocol):
    def find_by_activity_and_user(self, activity_id: UUID, user_id: UUID) -> Review | None: ...

    def list_by_activity(
        self, activity_id: UUID, limit: int | None = None, offset: int = 0
    ) -> list[Review]: ...

    def count_by_activity(self, activity_id: UUID) -> int: ...

    def list_ratings_by_activity(self, activity_id: UUID) -> list[int]: ...

    def save(self, review: Review) -> None: ...

    def update(self, review: Review) -> None: ...
